//! Bitmap fonts ported from `hardware/st7735/fonts.c`.
//!
//! Each glyph is `height` rows of u16; bit 15 is the leftmost pixel.
//! Glyphs start at ASCII 32 (space).

// All four fonts from the C code are kept, even those no screen uses yet.
#![allow(dead_code)]

pub struct Font {
    pub width: u16,
    pub height: u16,
    pub data: &'static [u16],
}

impl Font {
    /// Rows of the glyph for `ch`, falling back to '?' for non-ASCII.
    pub fn glyph(&self, ch: char) -> &[u16] {
        let index = match ch {
            ' '..='~' => ch as usize - 32,
            _ => '?' as usize - 32,
        };
        let h = self.height as usize;
        &self.data[index * h..(index + 1) * h]
    }
}

